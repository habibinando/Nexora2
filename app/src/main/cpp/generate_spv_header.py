#!/usr/bin/env python3
"""Compile Nexora GLSL compute shaders and generate the C++ SPIR-V header.

The generated header is a build output, not a source of hand-maintained bytecode.
glslangValidator targets Vulkan 1.0 so the kernels remain usable on Vulkan 1.0+
devices when their required baseline features are supported.
"""
from __future__ import annotations

import argparse
import pathlib
import struct
import subprocess
import tempfile

SHADERS = (
    ("matmul_tiled.comp", "spv_matmul_tiled"),
    ("adamw.comp", "spv_adamw"),
    ("swiglu.comp", "spv_swiglu"),
    ("swiglu_backward.comp", "spv_swiglu_backward"),
    ("rmsnorm.comp", "spv_rmsnorm"),
)


def compile_shader(compiler: str, source: pathlib.Path, output: pathlib.Path) -> bytes:
    cmd = [compiler, "-V", "--target-env", "vulkan1.0", "-Os", "-o", str(output), str(source)]
    subprocess.run(cmd, check=True)
    binary = output.read_bytes()
    if not binary or len(binary) % 4:
        raise RuntimeError(f"Invalid SPIR-V output from {source}: {len(binary)} bytes")
    words = struct.unpack("<" + "I" * (len(binary) // 4), binary)
    if words[0] != 0x07230203:
        raise RuntimeError(f"Invalid SPIR-V magic number for {source}")
    return binary


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--compiler", required=True)
    parser.add_argument("--source-dir", required=True, type=pathlib.Path)
    parser.add_argument("--output", required=True, type=pathlib.Path)
    args = parser.parse_args()

    arrays: list[str] = [
        "// Generated by generate_spv_header.py. Do not edit by hand.",
        "#pragma once",
        "#include <cstdint>",
        "",
    ]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="nexora-spv-") as tmp:
        tmpdir = pathlib.Path(tmp)
        for filename, symbol in SHADERS:
            source = args.source_dir / filename
            if not source.is_file():
                raise FileNotFoundError(f"Shader source not found: {source}")
            binary = compile_shader(args.compiler, source, tmpdir / (filename + ".spv"))
            words = struct.unpack("<" + "I" * (len(binary) // 4), binary)
            arrays.append(f"const uint32_t {symbol}[] = {{")
            for start in range(0, len(words), 8):
                arrays.append("    " + ", ".join(f"0x{word:08x}" for word in words[start:start + 8]) + ",")
            arrays.append("};")
            arrays.append(f"const uint32_t {symbol}_size = sizeof({symbol});")
            arrays.append("")

    args.output.write_text("\n".join(arrays) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
